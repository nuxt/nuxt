import { createHash } from 'node:crypto'

import type { Nuxt } from '@nuxt/schema'
import type { RsbuildPlugin, Rspack } from '@rsbuild/core'

import { SSRStylesPlugin as SSRStylesRspackPlugin } from '../../../webpack/src/plugins/ssr-styles.ts'
import { getGlobalCSSCacheGroup } from '../../../webpack/src/utils/options.ts'

/**
 * Inline the styles of components rendered on the server.
 */
export function SSRStylesPlugin (nuxt: Nuxt): RsbuildPlugin {
  return {
    name: 'nuxt:ssr-styles',
    setup (api) {
      const nuxtGlobalCSS = getGlobalCSSCacheGroup(nuxt)
      if (nuxtGlobalCSS) {
        api.modifyBundlerChain((chain, { environment }) => {
          if (environment.name !== 'client') { return }
          const splitChunks = chain.optimization.splitChunks.values() as Rspack.OptimizationSplitChunksOptions | false
          if (!splitChunks) { return }
          chain.optimization.splitChunks({
            ...splitChunks,
            cacheGroups: { ...splitChunks.cacheGroups, nuxtGlobalCSS },
          })
        })
      }

      if (!nuxt.options.ssr || nuxt.options.dev) { return }

      // Rsbuild has no equivalent: the Rspack plugin shared with the webpack builder collects
      // the CSS emitted by the client build and emits it as modules of the server build.
      const ssrStylesPlugin = new SSRStylesRspackPlugin(nuxt, {
        // scope IDs generated by `rspack-vue-loader`
        getVueLoaderHash: value => createHash('sha256').update(value).digest('hex').substring(0, 8),
        serverName: 'ssr',
      })
      api.modifyRspackConfig((config, { environment }) => {
        config.plugins ||= []
        config.plugins.push(ssrStylesPlugin as unknown as Rspack.RspackPluginInstance)
        if (environment.name === 'ssr') {
          // the server build needs the styles collected from the client build
          config.dependencies = ['client']
        }
      })
    },
  }
}
